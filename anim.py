def _title_color(t: float) -> str:
    t  = t % 1.0
    n  = len(_TITLE_KEYS) - 1
    lo = int(t * n)
    hi = min(lo + 1, n)
    f  = (t * n) - lo
    r  = int(_TITLE_KEYS[lo][0] + (_TITLE_KEYS[hi][0] - _TITLE_KEYS[lo][0]) * f)
    g  = int(_TITLE_KEYS[lo][1] + (_TITLE_KEYS[hi][1] - _TITLE_KEYS[lo][1]) * f)
    b  = int(_TITLE_KEYS[lo][2] + (_TITLE_KEYS[hi][2] - _TITLE_KEYS[lo][2]) * f)
    return f"\033[38;2;{r};{g};{b}m"



def animated_main_menu() -> None:
    """3d_diagonal ASCII art title with looping color cycle, then fast menu fade-in."""
    import shutil
    os.system("cls" if os.name == "nt" else "clear")

    term_w = shutil.get_terminal_size((80, 24)).columns

    NROWS     = len(_TITLE_ROWS)
    FRAMES    = 80        # total animation frames before menu appears
    LOOP_LEN  = 20        # frames per full color cycle — loops continuously
    MENU_OPTS = ["  [1] New Game", "  [2] Load Game", "  [0] Exit"]
    FINAL_C   = _rgb(200, 210, 255)

    # center the art based on the widest row
    art_w = max(len(r) for r in _TITLE_ROWS)
    pad   = max(0, (term_w - art_w) // 2)

    print()
    first = True
    for i in range(FRAMES):
        t   = (i / LOOP_LEN) % 1.0    # loops 0→1 continuously
        col = _title_color(t)

        if not first:
            sys.stdout.write(f"\033[{NROWS}A")
        first = False

        for row in _TITLE_ROWS:
            display = row[:max(1, term_w - pad - 1)]
            sys.stdout.write(f"\033[2K{col}{BOLD}{' '*pad}{display}{RESET}\n")
        sys.stdout.flush()
        time.sleep(0.04)

    # Divider
    div_w = min(52, term_w - 4)
    sys.stdout.write(f"\033[2K{_rgb(80,80,120)}  {'─'*div_w}{RESET}\n")
    print()

    # Menu fade-in
    FADE = 6
    first_m = True
    for step in range(FADE):
        frac = (step + 1) / FADE
        esc  = _rgb(int(60 + 140*frac), int(60 + 150*frac), int(80 + 175*frac))
        if not first_m:
            sys.stdout.write(f"\033[{len(MENU_OPTS)}A")
        for opt in MENU_OPTS:
            _clear_line()
            print(f"{esc}{opt}{RESET}")
        sys.stdout.flush()
        first_m = False
        time.sleep(0.025)

    # Settle
    sys.stdout.write(f"\033[{len(MENU_OPTS)}A")
    for opt in MENU_OPTS:
        _clear_line()
        print(f"{FINAL_C}{opt}{RESET}")
    sys.stdout.flush()
    print()

