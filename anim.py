def path_colored_header(title: str, path: str = "Human") -> None:
    """
    Like ascii_header() but cycles through a path-specific color palette
    instead of the default pink wisteria palette.

    path values: "Demon"    → white → red
                 "Human"    → white → blue  (Demon Slayer Corps)
                 "Civilian" → white → green

    Usage (in game_loop):
        from anim import path_colored_header
        path_colored_header("THE WORLD OF WISTERIA", player.path)
    """
    import sys as _sys, shutil as _sh, time as _time

    key  = _normalize_key(title)
    rows = WISTERIA_ART.get(key)

    if rows is None:
        term_w = _sh.get_terminal_size((80, 24)).columns
        pad    = max(0, (term_w - len(title)) // 2)
        print()
        print(f"\033[1m\033[38;2;200;210;255m{' ' * pad}{title}\033[0m")
        print()
        return

    palette = _PATH_KEYS.get(path, _PATH_KEYS["Human"])

    def _pcol(t: float) -> str:
        t  = t % 1.0
        n  = len(palette) - 1
        lo = int(t * n)
        hi = min(lo + 1, n)
        f  = (t * n) - lo
        r  = int(palette[lo][0] + (palette[hi][0] - palette[lo][0]) * f)
        g  = int(palette[lo][1] + (palette[hi][1] - palette[lo][1]) * f)
        b  = int(palette[lo][2] + (palette[hi][2] - palette[lo][2]) * f)
        return f"\033[38;2;{r};{g};{b}m"

    term_w = _sh.get_terminal_size((80, 24)).columns
    art_w  = max((len(r) for r in rows), default=0)
    pad    = max(0, (term_w - art_w) // 2)
    NROWS  = len(rows)
    FRAMES = 18

    print()
    first = True
    for i in range(FRAMES):
        t   = (i / FRAMES) * 0.75
        col = _pcol(t)
        if not first:
            _sys.stdout.write(f"\033[{NROWS}A")
        first = False
        for row in rows:
            _sys.stdout.write(f"\033[2K{col}\033[1m{' ' * pad}{row}\033[0m\n")
        _sys.stdout.flush()
        _time.sleep(0.025)

    print()